import fs from "node:fs";
import path from "node:path";
import type { TransformationManifest } from "./types.js";

/**
 * Writes a Markdown report file inside `reports/<body-part-id>/<fileName>` with a metadata comment header.
 */
export function saveMarkdownReportFile(
  reportDir: string,
  fileName: string,
  manifest: TransformationManifest,
  markdownContent: string,
  modelName: string,
  langCode = "en-US"
): string {
  fs.mkdirSync(reportDir, { recursive: true });
  const filePath = path.join(reportDir, fileName);

  // Strip any existing HTML metadata comment at the top before prepending fresh header
  const cleanedMarkdown = markdownContent
    .replace(/^<!--\s*Generated by Doctor Lens.*?-->\s*/is, "")
    .trim();

  const header = [
    `<!-- Generated by Doctor Lens | Case: ${manifest.bodyPartId} | Lang: ${langCode} | Model: ${modelName} | Date: ${new Date().toISOString()} -->`,
    "",
  ].join("\n");

  const fullContent = `${header}${cleanedMarkdown}\n`;
  fs.writeFileSync(filePath, fullContent, "utf-8");
  return filePath;
}

/**
 * Formats and writes the primary diagnostic report to `reports/<body-part-id>/report.md`.
 */
export function saveDiagnosticReport(
  reportDir: string,
  manifest: TransformationManifest,
  geminiMarkdown: string,
  modelName: string
): string {
  return saveMarkdownReportFile(
    reportDir,
    "report.md",
    manifest,
    geminiMarkdown,
    modelName,
    "en-US"
  );
}
